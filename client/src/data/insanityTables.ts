/** 按 1D10 取即时症状。 */
export function rollImmediateSymptom(roll: number): InsanitySymptom {
  const n = Math.max(1, Math.min(10, roll))
  return IMMEDIATE_BOUT_SYMPTOMS[n - 1]
}

/** 按 1D10 取总结症状。 */
export function rollSummarySymptom(roll: number): InsanitySymptom {
  const n = Math.max(1, Math.min(10, roll))
  return SUMMARY_BOUT_SYMPTOMS[n - 1]
}
