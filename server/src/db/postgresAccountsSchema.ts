import type { PoolClient } from 'pg'

export class IncompatiblePostgresAccountSchemaError extends Error {
  constructor() {
    super('Incompatible PostgreSQL account/settings schema or permissions')
  }
}

/** The caller holds the migration lock until this schema is ready to serve. */
export async function initializePostgresAccounts(client: PoolClient): Promise<void> {
  await client.query(`
    CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username TEXT COLLATE "C" NOT NULL UNIQUE,
      password_hash TEXT NOT NULL,
      created_at BIGINT NOT NULL
    );
    CREATE TABLE IF NOT EXISTS settings (
      user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
      data TEXT NOT NULL
    );
  `)

  // Validate existing tables without inserting probe accounts or consuming
  // IDs. Additional columns are allowed if current inserts can omit them.
  const result = await client.query<{ compatible: boolean }>(`
    WITH expected_columns (table_name, column_name, data_type) AS (
      VALUES
        ('users', 'id', 'bigint'),
        ('users', 'username', 'text'),
        ('users', 'password_hash', 'text'),
        ('users', 'created_at', 'bigint'),
        ('settings', 'user_id', 'bigint'),
        ('settings', 'data', 'text')
    ),
    actual_columns AS (
      SELECT *
      FROM information_schema.columns
      WHERE table_schema = current_schema() AND table_name IN ('users', 'settings')
    ),
    actual_constraints AS (
      SELECT conrelid, pg_get_constraintdef(oid) AS definition
      FROM pg_constraint
      WHERE conrelid IN ('users'::regclass, 'settings'::regclass)
        AND convalidated AND NOT condeferrable
    )
    SELECT
      NOT EXISTS (
        SELECT 1 FROM expected_columns expected
        LEFT JOIN actual_columns actual USING (table_name, column_name)
        WHERE actual.data_type IS DISTINCT FROM expected.data_type
          OR actual.is_nullable IS DISTINCT FROM 'NO'
          OR (expected.column_name = 'id' AND actual.identity_generation IS DISTINCT FROM 'BY DEFAULT')
          OR (expected.column_name = 'username' AND actual.collation_name IS DISTINCT FROM 'C')
      )
      AND NOT EXISTS (
        SELECT 1 FROM actual_columns actual
        LEFT JOIN expected_columns expected USING (table_name, column_name)
        WHERE expected.column_name IS NULL AND actual.is_nullable = 'NO'
          AND actual.column_default IS NULL AND actual.is_identity = 'NO' AND actual.is_generated = 'NEVER'
      )
      AND EXISTS (
        SELECT 1 FROM actual_constraints WHERE conrelid = 'users'::regclass AND definition = 'PRIMARY KEY (id)'
      )
      AND EXISTS (
        SELECT 1 FROM actual_constraints WHERE conrelid = 'users'::regclass AND definition = 'UNIQUE (username)'
      )
      AND EXISTS (
        SELECT 1 FROM actual_constraints WHERE conrelid = 'settings'::regclass AND definition = 'PRIMARY KEY (user_id)'
      )
      AND EXISTS (
        SELECT 1 FROM actual_constraints
        WHERE conrelid = 'settings'::regclass AND definition = 'FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE'
      )
      AND has_table_privilege('users', 'SELECT') AND has_table_privilege('users', 'INSERT')
      AND has_column_privilege('users', 'id', 'UPDATE')
      AND has_table_privilege('settings', 'SELECT') AND has_table_privilege('settings', 'INSERT')
      AND has_column_privilege('settings', 'data', 'UPDATE')
      AND NOT row_security_active('users') AND NOT row_security_active('settings')
      AS compatible
  `)
  if (!result.rows[0]?.compatible) throw new IncompatiblePostgresAccountSchemaError()
}
